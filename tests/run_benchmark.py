#!/usr/bin/env python3
"""OpenVerifiers — benchmark runner.

Runs every entry in tests/problems.py through verify_physics, compares the answer
against the known correct value, and writes RESULTS.md at the repo root.

Usage:  python -m openverifiers.tests.run_benchmark
"""

from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", ".."))

from openverifiers import verify_physics  # noqa: E402
from openverifiers.tests.problems import BENCH  # noqa: E402


def close(a, b, tol=1e-6) -> bool:
    try:
        af = float(a)
        bf = float(b)
    except (TypeError, ValueError):
        return False
    return abs(af - bf) <= tol * max(1.0, abs(bf))


def main() -> int:
    rows = []
    passed = 0
    for pid, text, target, expected, explicit in BENCH:
        res = verify_physics(text, explicit=explicit or None, explicit_target=target)
        ok = res.status == "RESOLVED" and close(res.answer, expected)
        if ok:
            passed += 1
        rows.append((pid, res.status, str(res.answer), ok))

    total = len(rows)
    pct = 100.0 * passed / total

    lines = []
    lines.append("# OpenVerifiers — Physics Slice Benchmark Results\n")
    lines.append(f"- Date: generated by `python -m openverifiers.tests.run_benchmark`")
    lines.append(f"- Problems: {total}")
    lines.append(f"- Passed: {passed}")
    lines.append(f"- Failed: {total - passed}")
    lines.append(f"- Pass rate: {pct:.1f}%\n")
    lines.append("| id | status | answer | pass |")
    lines.append("|---|---|---|---|")
    for pid, status, ans, ok in rows:
        lines.append(f"| {pid} | {status} | {ans} | {'✅' if ok else '❌'} |")
    lines.append("")
    lines.append("Notes:")
    lines.append("- Pass = status `RESOLVED` and answer within 1e-6 relative tolerance of the known correct value.")
    lines.append("- A `UNKNOWN` verdict counts as a fail here: benchmark demands a resolved number.")

    text = "\n".join(lines)
    root = os.path.join(os.path.dirname(__file__), "..")
    out = os.path.join(root, "RESULTS.md")
    with open(out, "w") as fh:
        fh.write(text)
    print(text)
    print(f"\nwrote {out}")
    return 0 if passed == total else 1


if __name__ == "__main__":
    raise SystemExit(main())